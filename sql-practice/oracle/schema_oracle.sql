-- ============================================================
-- schema_oracle.sql
-- EC題材（customers / products / orders / order_items）のOracle版DDL
-- 対象: Oracle Database 23ai Free
--
-- SQLite版（../schema.sql）との主な違い（詳細は differences.md も参照）:
--   - SQLiteは動的型付け（型アフィニティ）。列にどんな値でもほぼ入る。
--     Oracleは厳密な型システムで、型と長さを守らないとエラーになる。
--   - SQLiteの TEXT     -> Oracleの VARCHAR2(n)（長さの指定が必須）
--   - SQLiteの INTEGER   -> Oracleの NUMBER や NUMBER(p, s)
--   - SQLiteの「TEXTに日付文字列を入れる」-> Oracleは専用の DATE 型を持つ
--   - SQLiteの INTEGER PRIMARY KEY は自動的にrowidの別名になり暗黙で採番される。
--     Oracleでは自動採番を明示的に定義する必要がある（後述）。
-- ============================================================

